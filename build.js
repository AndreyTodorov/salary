/* Bakes the interface text and the search-engine metadata into the static pages:
   index.html (English, also the default page) and de/index.html (German), the explanation pages
   how-it-works/ and de/so-wird-gerechnet/ (text in _guide/), the privacy policy privacy/ and
   de/datenschutz/ (text in _privacy/), the Impressum impressum/ and de/impressum/ (text in
   _impressum/), and sitemap.xml.
   index.html is the source: edit it, then run `node build.js`. `node build.js --check` fails when
   any generated file is out of date.
   Every page shows the date its content last changed: the page stores a hash of its content without
   the date, and the build keeps the stored date while that hash still matches, otherwise uses today.
   For the calculator the content includes tax.js; for the text pages it leaves out styles and scripts. */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const T = require('./tax.js');
const I18N = require('./i18n.js');

const ORIGIN = 'https://salary.atdrv.eu';
const LANGS = ['en', 'de'];
const LOCALE = { en: 'en_GB', de: 'de_DE' };
const OTHER = { en: 'de', de: 'en' };
const NAME = { en: 'English', de: 'Deutsch' };

const COMMON = {
  year: T.Y.YEAR,
  zbAvg: String(T.Y.ZB_AVERAGE).replace('.', ','),
  cardLimit: new Intl.NumberFormat('de-DE', { maximumFractionDigits: 0 }).format(T.Y.SACHBEZUG_LIMIT / 100) + ' €',
};
const t = (lang, key) => (I18N[lang][key] ?? I18N.en[key]).replace(/\{(\w+)\}/g, (_, k) => COMMON[k] ?? '');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Site paths; a page's file is its path plus index.html.
const PATHS = {
  calc: { en: '/', de: '/de/' },
  guide: { en: t('en', 'guidePath'), de: t('de', 'guidePath') },
  privacy: { en: t('en', 'privacyPath'), de: t('de', 'privacyPath') },
  impressum: { en: t('en', 'impressumPath'), de: t('de', 'impressumPath') },
};

// Text pages: where their content lives and which interface strings name them.
const DOCS = {
  guide: { dir: '_guide', docTitle: 'guideDocTitle', title: 'guideTitle', lede: 'guideLede', description: 'guideDescription', type: 'Article' },
  privacy: { dir: '_privacy', docTitle: 'privacyDocTitle', title: 'privacyTitle', lede: 'privacyLede', description: 'privacyDescription', type: 'WebPage' },
  impressum: { dir: '_impressum', docTitle: 'impressumDocTitle', title: 'impressumTitle', lede: 'impressumLede', description: 'impressumDescription', type: 'WebPage' },
};
const url = (kind, lang) => ORIGIN + PATHS[kind][lang];

// Placeholders for the "last updated" line, filled in by stamp().
const DATE = '@@date@@', DATE_TEXT = '@@dateText@@', HASH = '@@hash@@';
const TODAY = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Berlin' }).format(new Date()); // YYYY-MM-DD
const updatedLine = (lang) => `<p class="updated" data-hash="${HASH}">${esc(t(lang, 'updated'))} <time datetime="${DATE}">${DATE_TEXT}</time></p>`;

// The preview image belongs to the page's main node: the object itself, or the first entry of an @graph.
function withImage(ld, image) {
  const context = { '@context': 'https://schema.org' };
  if (!ld['@graph']) return { ...context, image, ...ld };
  const [main, ...rest] = ld['@graph'];
  return { ...context, ...ld, '@graph': [{ ...main, image }, ...rest] };
}

function seo(kind, lang, title, description, ld) {
  const image = `${ORIGIN}/og-${lang}.png`;
  return [
    '<!-- seo: generated by build.js -->',
    `<title>${esc(title)}</title>`,
    `<meta name="description" content="${esc(description)}">`,
    `<link rel="canonical" href="${url(kind, lang)}">`,
    `<link rel="alternate" hreflang="en" href="${url(kind, 'en')}">`,
    `<link rel="alternate" hreflang="de" href="${url(kind, 'de')}">`,
    `<link rel="alternate" hreflang="x-default" href="${url(kind, 'en')}">`,
    `<meta property="og:type" content="${kind === 'guide' ? 'article' : 'website'}">`,
    `<meta property="og:url" content="${url(kind, lang)}">`,
    `<meta property="og:title" content="${esc(title)}">`,
    `<meta property="og:description" content="${esc(description)}">`,
    `<meta property="og:locale" content="${LOCALE[lang]}">`,
    `<meta property="og:locale:alternate" content="${LOCALE[OTHER[lang]]}">`,
    `<meta property="og:image" content="${image}">`,
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    `<meta property="og:image:alt" content="${esc(title)}">`,
    '<meta name="twitter:card" content="summary_large_image">',
    `<script type="application/ld+json">${JSON.stringify(withImage(ld, image)).replace(/</g, '\\u003c')}</script>`,
    '<!-- /seo -->',
  ].join('\n');
}

function calcPage(source, lang) {
  const title = t(lang, 'docTitle'), description = t(lang, 'description');
  const head = seo('calc', lang, title, description, {
    '@type': 'WebApplication',
    name: title,
    url: url('calc', lang),
    description,
    inLanguage: lang,
    applicationCategory: 'FinanceApplication',
    operatingSystem: 'Any',
    browserRequirements: 'Requires JavaScript',
    isAccessibleForFree: true,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'EUR' },
    dateModified: DATE,
  });
  let html = source
    .replace(/<html lang="\w+">/, `<html lang="${lang}">`)
    .replace(/<!-- seo: generated by build\.js -->[\s\S]*?<!-- \/seo -->/, () => head)
    .replace(/<p class="updated"[^>]*>[\s\S]*?<\/p>/, () => updatedLine(lang))
    // Text of every data-i18n element, so crawlers and no-JS visitors see the page in its language.
    .replace(/<(\w+)([^>]*\sdata-i18n="(\w+)"[^>]*)>[^<]*<\/\1>/g,
      (_, tag, attrs, key) => `<${tag}${attrs}>${esc(t(lang, key))}</${tag}>`);
  if (lang === 'de') {
    // de/index.html sits one folder down: point relative asset paths back up.
    html = html
      .replace(/(\s(?:src|href)=")(?![a-z]+:|#|\/)/g, '$1../')
      .replace(/url\("(?![a-z]+:|\/)/g, 'url("../');
  }
  // Links whose target depends on the language, such as the explanation page.
  return html.replace(/href="[^"]*"(\s+data-i18n-href="(\w+)")/g, (_, attr, key) => `href="${t(lang, key)}"${attr}`);
}

// The worked example on the explanation page, computed with the calculator's defaults.
function example(lang) {
  const r = T.calculate({ ...T.DEFAULTS, thirteenth: false }, 500000).regular;
  const n = new Intl.NumberFormat(lang === 'de' ? 'de-DE' : 'en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const eur = (c) => (lang === 'de' ? `${n.format(c / 100)}&nbsp;€` : `€${n.format(c / 100)}`);
  const rows = ['gross', 'incomeTax', 'soli', 'church', 'health', 'care', 'pension', 'unemployment', 'net']
    .filter((k) => k === 'gross' || k === 'net' || r[k] > 0)
    .map((k) => `    <tr${k === 'net' ? ' class="total"' : ''}><td>${esc(t(lang, 'row_' + k))}</td>`
      + `<td class="num">${k === 'gross' || k === 'net' ? '' : '−&nbsp;'}${eur(r[k])}</td></tr>`);
  return `<div class="table-wrap"><table>\n  <tbody>\n${rows.join('\n')}\n  </tbody>\n</table></div>`;
}

function docPage(source, lang, kind) {
  const doc = DOCS[kind];
  const title = t(lang, doc.docTitle), description = t(lang, doc.description);
  const head = seo(kind, lang, title, description, {
    '@graph': [
      { '@type': doc.type, headline: t(lang, doc.title), description, inLanguage: lang, url: url(kind, lang), dateModified: DATE },
      { '@type': 'BreadcrumbList', itemListElement: [
        { '@type': 'ListItem', position: 1, name: t(lang, 'title'), item: url('calc', lang) },
        { '@type': 'ListItem', position: 2, name: t(lang, doc.title), item: url(kind, lang) },
      ] },
    ],
  });
  // Same look as the calculator: its theme script, theme colour and styles, with root-relative fonts.
  const themeScript = source.match(/<script>\n {2}\/\/ Apply the remembered theme[\s\S]*?<\/script>/)[0];
  const themeColor = source.match(/<meta name="theme-color"[^>]*>/)[0];
  const style = source.match(/<style>[\s\S]*?<\/style>/)[0].replace(/url\("(?![a-z]+:|\/)/g, 'url("/');
  const content = fs.readFileSync(path.join(__dirname, doc.dir, `${lang}.html`), 'utf8')
    .replace('{{example}}', () => example(lang)).trimEnd();
  const other = OTHER[lang];
  return `<!doctype html>
<html lang="${lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
${head}
${themeColor}
${themeScript}
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
${style}
</head>
<body>
<div class="page">
  <header class="top">
    <div class="brand">
      <p class="crumb"><a href="${PATHS.calc[lang]}">${esc(t(lang, 'title'))}</a></p>
      <h1>${esc(t(lang, doc.title))}</h1>
      <p class="lede">${esc(t(lang, doc.lede))}</p>
    </div>
    <div class="top-actions">
      <a class="btn" href="${PATHS[kind][other]}" hreflang="${other}" lang="${other}">${NAME[other]}</a>
    </div>
  </header>
  <main class="card prose">
${content}
  </main>
  <footer>
    <p>${esc(t(lang, 'footer'))}</p>
    <p><a href="${PATHS.calc[lang]}">${esc(t(lang, 'title'))}</a> · <a href="${PATHS.guide[lang]}">${esc(t(lang, 'guideLink'))}</a> · <a href="${PATHS.privacy[lang]}">${esc(t(lang, 'privacyLink'))}</a> · <a href="${PATHS.impressum[lang]}">${esc(t(lang, 'impressumLink'))}</a></p>
    ${updatedLine(lang)}
  </footer>
</div>
</body>
</html>
`;
}

// Fills in a page's date: the stored one while its content is unchanged, otherwise today.
function stamp(name, lang, draft, content) {
  const hash = crypto.createHash('sha256').update(content).digest('hex').slice(0, 12);
  const file = path.join(__dirname, name);
  const stored = fs.existsSync(file) && fs.readFileSync(file, 'utf8').match(/<p class="updated" data-hash="(\w+)">[^<]*<time datetime="([\d-]+)">/);
  const date = stored && stored[1] === hash ? stored[2] : TODAY;
  const text = new Intl.DateTimeFormat(lang === 'de' ? 'de-DE' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' })
    .format(new Date(`${date}T12:00:00Z`));
  return { date, html: draft.replaceAll(HASH, hash).replaceAll(DATE_TEXT, text).replaceAll(DATE, date) };
}

function sitemap(dates) {
  const entries = Object.keys(PATHS).flatMap((kind) => LANGS.map((lang) => [
    '  <url>',
    `    <loc>${url(kind, lang)}</loc>`,
    `    <lastmod>${dates[kind][lang]}</lastmod>`,
    ...[...LANGS, 'x-default'].map((h) => `    <xhtml:link rel="alternate" hreflang="${h}" href="${url(kind, h === 'x-default' ? 'en' : h)}"/>`),
    '  </url>',
  ].join('\n')));
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.join('\n')}
</urlset>
`;
}

const source = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
const TAX_JS = fs.readFileSync(path.join(__dirname, 'tax.js'), 'utf8');
const outputs = {}, dates = {};
for (const kind of Object.keys(PATHS)) {
  dates[kind] = {};
  for (const lang of LANGS) {
    const name = PATHS[kind][lang].slice(1) + 'index.html';
    const draft = kind === 'calc' ? calcPage(source, lang) : docPage(source, lang, kind);
    const content = kind === 'calc' ? draft + TAX_JS : draft.replace(/<style>[\s\S]*?<\/style>|<script>[\s\S]*?<\/script>/g, '');
    const page = stamp(name, lang, draft, content);
    outputs[name] = page.html;
    dates[kind][lang] = page.date;
  }
}
outputs['sitemap.xml'] = sitemap(dates);

const check = process.argv.includes('--check');
const stale = [];
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(__dirname, name);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
  stale.push(name);
  if (!check) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
if (check && stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run: node build.js`);
  process.exit(1);
}
console.log(stale.length ? `Wrote ${stale.join(', ')}` : 'Up to date');
